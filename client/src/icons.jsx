// Universal Nav Icon Helper with proper Lucide mapping
export function NavIcon({ name, size = 18, style = {} }) {
  const iconProps = { size, style: { display: 'inline-block', verticalAlign: 'middle', marginRight: 8, ...style } };
  switch (name) {
    case 'Home':
    case 'Overview':
      return <Home {...iconProps} />;
    case 'Account Search':
      return <Search {...iconProps} />;
    case 'Connected Accounts':
    case 'Integrations':
      return <Share2 {...iconProps} />;
    case 'Dataset Analysis':
    case 'Bulk Scan':
      return <Database {...iconProps} />;
    case 'Model Training':
    case 'ML Retrain Lab':
    case 'ML Benchmarks':
    case 'ML Retrain & Calibration':
    case 'ML Lab':
    case 'Threat Radar & ML Lab':
      return <Sliders {...iconProps} />;
    case 'Case Review & Governance':
      return <Briefcase {...iconProps} />;
    case 'Scan History':
    case 'Audit Log':
      return <History {...iconProps} />;
    case 'Manual Analyzer':
    case 'Analyzer':
      return <Crosshair {...iconProps} />;
    case 'Reports':
      return <FileText {...iconProps} />;
    case 'Blockchain & Compliance':
    case 'Blockchain':
      return <Link2 {...iconProps} />;
    case 'Developer API':
    case 'Developer API Quotas':
    case 'Developer API Keys':
      return <Terminal {...iconProps} />;
    case 'Payment Reviews':
      return <CreditCard {...iconProps} />;
    case 'Users':
      return <Users {...iconProps} />;
    case 'Upgrade Plan':
    case 'Unlock Features':
      return <Unlock {...iconProps} />;
    case 'Settings':
      return <Settings {...iconProps} />;
    default:
      return <LayoutDashboard {...iconProps} />;
  }
}

